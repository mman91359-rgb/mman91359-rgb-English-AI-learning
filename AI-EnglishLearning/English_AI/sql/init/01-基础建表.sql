-- 01-基础建表.sql
CREATE DATABASE IF NOT EXISTS english_ai DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE english_ai;

-- 用户表
CREATE TABLE IF NOT EXISTS `user` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '用户ID',
  `username` VARCHAR(50) NOT NULL UNIQUE COMMENT '用户名',
  `password` VARCHAR(100) NOT NULL COMMENT '加密密码',
  `nickname` VARCHAR(50) COMMENT '昵称',
  `avatar` VARCHAR(255) COMMENT '头像地址',
  `email` VARCHAR(100) COMMENT '邮箱',
  `ability_radar` TEXT COMMENT '能力雷达JSON',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT DEFAULT 0 COMMENT '逻辑删除 0未删1删除'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户表';

-- 单词表
CREATE TABLE IF NOT EXISTS `word` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `word` VARCHAR(50) NOT NULL COMMENT '英文单词',
  `phonetic` VARCHAR(100) COMMENT '音标',
  `chinese` TEXT COMMENT '中文释义',
  `example` TEXT COMMENT '例句',
  `example_cn` TEXT COMMENT '例句翻译',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='单词库';

-- 用户单词学习记录表（艾宾浩斯）
CREATE TABLE IF NOT EXISTS `user_word` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `user_id` BIGINT NOT NULL COMMENT '用户ID',
  `word_id` BIGINT NOT NULL COMMENT '单词ID',
  `memory_stage` INT DEFAULT 0 COMMENT '记忆阶段 0~6',
  `next_review_time` DATETIME COMMENT '下次复习时间',
  `review_count` INT DEFAULT 0 COMMENT '复习次数',
  `is_mastered` TINYINT DEFAULT 0 COMMENT '是否掌握 0否1是',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT DEFAULT 0,
  INDEX idx_userid (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户单词学习记录';

-- 练习题
CREATE TABLE IF NOT EXISTS `exercise` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `word_id` BIGINT COMMENT '关联单词ID',
  `question_type` VARCHAR(20) NOT NULL COMMENT '题型：choice/blank/judge',
  `question_content` TEXT NOT NULL COMMENT '题干',
  `options` TEXT COMMENT '选项JSON',
  `answer` TEXT NOT NULL COMMENT '标准答案',
  `analysis` TEXT COMMENT '解析',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='练习题';

-- 用户答题记录
CREATE TABLE IF NOT EXISTS `user_exercise_record` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `user_id` BIGINT NOT NULL,
  `exercise_id` BIGINT NOT NULL,
  `user_answer` TEXT COMMENT '用户作答',
  `is_correct` TINYINT NOT NULL COMMENT '是否答对 0错1对',
  `submit_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted` TINYINT DEFAULT 0,
  INDEX idx_userid (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户答题记录';

-- AI对话历史
CREATE TABLE IF NOT EXISTS `ai_chat` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `user_id` BIGINT NOT NULL,
  `role` VARCHAR(20) NOT NULL COMMENT 'user / assistant',
  `content` TEXT NOT NULL COMMENT '对话内容',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `deleted` TINYINT DEFAULT 0,
  INDEX idx_userid (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI聊天记录';
